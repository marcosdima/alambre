import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const ICONS_DIR = path.resolve(__dirname, '../assets/icons');
const OUTPUT_FILE = path.resolve(__dirname, '../src/components/icons/generated.ts');

function camelCase(str) {
  return str.replace(/[-_]+(.)?/g, (_, c) => c ? c.toUpperCase() : '');
}

function pascalCase(str) {
  const camel = camelCase(str);
  return camel.charAt(0).toUpperCase() + camel.slice(1);
}

function parseSvgPaths(svgContent) {
  const pathRegex = /<path[^>]*d="([^"]+)"[^>]*>/gi;
  let paths = [];
  let match;
  while ((match = pathRegex.exec(svgContent)) !== null) {
    paths.push(match[1]);
  }
  return paths;
}

function main() {
  if (!fs.existsSync(ICONS_DIR)) {
    fs.mkdirSync(ICONS_DIR, { recursive: true });
  }

  const files = fs.readdirSync(ICONS_DIR).filter(f => f.endsWith('.svg'));
  
  if (files.length === 0) {
    console.log('No SVG files found in assets/icons. Skipping generation.');
    return;
  }

  let fileContent = `// AUTO-GENERATED BY scripts/generate-icons.js\n// DO NOT EDIT MANUALLY.\n\n`;
  fileContent += `import { createAnimatedIcon } from './base/createAnimatedIcon';\n\n`;

  const exportsList = [];

  for (const file of files) {
    const name = pascalCase(file.replace('.svg', '')) + 'Icon';
    const content = fs.readFileSync(path.join(ICONS_DIR, file), 'utf8');
    
    // Support standard 24x24 icons
    const paths = parseSvgPaths(content);
    if (paths.length === 0) continue;

    fileContent += `export const ${name} = createAnimatedIcon({\n`;
    fileContent += `  paths: [\n`;
    paths.forEach(p => {
      fileContent += `    '${p}',\n`;
    });
    fileContent += `  ]\n});\n\n`;
    
    exportsList.push(name);
  }

  fs.writeFileSync(OUTPUT_FILE, fileContent);
  console.log(`Successfully generated ${exportsList.length} icons into ${OUTPUT_FILE}`);
}

main();
